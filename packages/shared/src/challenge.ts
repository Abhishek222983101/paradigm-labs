export type Challenge = { word: string; fingers: number }

export function newChallenge(): Challenge {
  const words = [...new Set(CHALLENGE_WORDS)]
  return { word: words[randomInt(words.length)] as string, fingers: randomInt(1, 6) }
}

/** Compact public form stored on the Arkiv claim, e.g. "mango:3". Not secret: it's shown on camera. */
export function encodeChallenge(c: Challenge): string {
  return `${c.word}:${c.fingers}`
}

export function decodeChallenge(s: string): Challenge | null {
  const m = /^([a-z-]{2,20}):([1-5])$/.exec(s)
  return m ? { word: m[1] as string, fingers: Number(m[2]) } : null
}
